<?php

declare(strict_types=1);

namespace Atlas\Pca\Tests;

use Atlas\Pca\Actions;
use Atlas\Pca\ActionsBuild;
use Atlas\Pca\ActionsBuiltin;
use Atlas\Pca\ActionsDerive;
use Atlas\Pca\IntentWb;
use Atlas\Pca\Num;
use Atlas\Pca\Obj;
use PHPUnit\Framework\TestCase;

require_once __DIR__ . '/../src/ActionsBuild.php';
require_once __DIR__ . '/../src/ActionsBuiltin.php';

/** Group 32 mutation kills for src/ActionsBuild.php: the pack size limit, duplicate verbs, the MCP tool map, generated types and pack verification. */
final class ActionsSurvivorKill32ActionsBuildTest extends TestCase
{
    private const HEAD = "// Generated by `pca actions build`. Do not edit.\n\n";
    private const TAIL = "\n}\n\nexport interface ActionParams {\n  \"a.b\": ABParams;\n}\n\nexport type ActionVerb = keyof ActionParams;\n";

    protected function setUp(): void
    {
        set_error_handler(static function (int $no, string $msg): bool {
            throw new \ErrorException($msg, 0, $no);
        });
    }

    protected function tearDown(): void
    {
        restore_error_handler();
    }

    private static function cfg(): Obj
    {
        return Obj::of(['ns' => 'acme', 'version' => '1.0.0', 'stability' => 'stable', 'site' => 'https://example.com', 'aud' => 'aud']);
    }

    private static function thrown(\Closure $f): string
    {
        try {
            $f();
        } catch (\Throwable $e) {
            return get_class($e) . ': ' . $e->getMessage();
        }
        return 'no throw';
    }

    private static function params(array $p): Obj
    {
        $o = new Obj();
        foreach ($p as $k => $type) {
            $o->set((string)$k, Obj::of(['type' => $type]));
        }
        return $o;
    }

    private static function typesOf(Obj $params): string
    {
        return ActionsBuild::generateTypes([Obj::of(['verb' => 'a.b', 'params' => $params])]);
    }

    /** Exactly 4096 defs are within the unsharded limit (the duplicate check runs); 4097 are refused with the count. */
    public function testThePackSizeLimit(): void
    {
        $d = Obj::of(['verb' => 'a.b']);
        self::assertSame(4096, ActionsBuild::MAX_PACK_DEFS);
        self::assertSame("InvalidArgumentException: verb 'a.b' appears twice", self::thrown(static fn() => ActionsBuild::buildArtifacts(array_fill(0, 4096, $d), self::cfg(), [])));
        self::assertSame('InvalidArgumentException: a pack above 4096 defs must be sharded (4097 given)', self::thrown(static fn() => ActionsBuild::buildArtifacts(array_fill(0, 4097, $d), self::cfg(), [])));
    }

    /** Two defs with one verb are refused, naming it. */
    public function testADuplicateVerbIsRefused(): void
    {
        $defs = [Obj::of(['verb' => 'a.c']), Obj::of(['verb' => 'a.c'])];
        self::assertSame("InvalidArgumentException: verb 'a.c' appears twice", self::thrown(static fn() => ActionsBuild::buildArtifacts($defs, self::cfg(), [])));
    }

    /** A def with an MCP binding lands in the tool map under its tool name, with its verb and annotations. */
    public function testTheMcpToolMap(): void
    {
        $reg = Actions::coreRegistry();
        $d = ActionsBuiltin::builtinDefs()[0]->without('bindings');
        $d->set('bindings', Obj::of(['mcp' => Obj::of(['tool' => 'the_tool'])]));
        $tools = ActionsBuild::buildArtifacts([$d], self::cfg(), $reg)->get('mcp')->get('tools');
        self::assertSame(['the_tool'], $tools->keys());
        $t = $tools->get('the_tool');
        self::assertSame(['verb', 'annotations'], $t->keys());
        self::assertSame($d->get('verb'), $t->get('verb'));
        self::assertSame(ActionsDerive::mcpAnnotationsOf($d, ActionsDerive::effectiveWith($d, $reg, null)), $t->get('annotations'));
    }

    /** toolActionMapOf skips a def without bindings: an unknown tool maps to null. */
    public function testToolActionMapSkipsUnboundDefs(): void
    {
        self::assertNull((ActionsBuild::toolActionMapOf([Obj::of(['verb' => 'a.b'])]))('t', null));
    }

    /** Numeric parameter names are rendered as quoted keys. */
    public function testNumericParamNames(): void
    {
        self::assertSame(self::HEAD . "export interface ABParams {\n  \"1\": number;\n  \"2\": boolean;" . self::TAIL, self::typesOf(self::params([1 => 'integer', 2 => 'boolean'])));
    }

    /** Keys are ordered per level: the nested `a` comes before `a-b` although `a-b` sorts first as a full name. */
    public function testKeysAreOrderedPerLevel(): void
    {
        self::assertSame(self::HEAD . "export interface ABParams {\n  a: {\n    x: number;\n  };\n  \"a-b\": boolean;" . self::TAIL,
            self::typesOf(self::params(['a-b' => 'boolean', 'a.x' => 'integer'])));
    }

    /** A def without parameters gets an empty interface. */
    public function testAnEmptyInterface(): void
    {
        self::assertSame(self::HEAD . "export interface ABParams {\n" . self::TAIL, self::typesOf(new Obj()));
    }

    /** packConsistencyError: 4096 defs are within the limit (each def is then validated); a bad def is named by its verb or '?'; an empty pack is malformed. */
    public function testPackConsistencyErrors(): void
    {
        $pack = static fn(array $defs): Obj => Obj::of(['v' => new Num('1'), 'kind' => 'pca-action-pack', 'defs' => $defs]);
        $d = Obj::of(['verb' => 'a.b']);
        self::assertSame('def ' . IntentWb::jsStr('a.b') . ': ' . Actions::validateDef($d), ActionsBuild::packConsistencyError($pack(array_fill(0, 4096, $d)), []));
        self::assertSame('def ?: ' . Actions::validateDef('x'), ActionsBuild::packConsistencyError($pack(['x']), []));
        $nv = Obj::of(['v' => 1]);
        self::assertSame('def ?: ' . Actions::validateDef($nv), ActionsBuild::packConsistencyError($pack([$nv]), []));
        self::assertSame('malformed pack: a pack has at least one def', ActionsBuild::packConsistencyError($pack([]), []));
    }

    /** The first registry key with the signature's kid is the one used; a key list that is not of objects is a verification error. */
    public function testVerifySignedPackKeys(): void
    {
        $reg = Actions::coreRegistry();
        $def = ActionsBuiltin::builtinDefs()[0];
        $pack = Obj::of(['v' => new Num('1'), 'kind' => 'pca-action-pack', 'defs' => [$def], 'root' => Actions::packRoot([Actions::defDigest($def)]),
            'traits_digest' => Actions::traitsDigest($reg)]);
        $secret = hash('sha256', 'atlas-pca-conformance/g32-pack', true);
        $signed = ActionsBuild::signPack($pack, 'k1', $secret, $reg);
        $keys = [ActionsBuild::packKeyOf('k1', $secret), Obj::of(['kid' => 'k1', 'alg' => 'none'])];
        self::assertSame(['ok' => true], ActionsBuild::verifySignedPack($signed, $keys, $reg));
        self::assertSame(['ok' => false, 'reason' => 'pack verification error: Call to a member function get() on int'], ActionsBuild::verifySignedPack($signed, [5], $reg));
    }
}
